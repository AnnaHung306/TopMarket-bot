import assert from 'node:assert/strict';
import {reconcileRefunds,SIG} from './worker/index.js';
const wallet='0x'+'1'.repeat(40),box='0x'+'2'.repeat(40),other='0x'+'3'.repeat(40),usdc='0x833589fcd6edb6e08f4c7c32d4f71b54bda02913',tx='0x'+'a'.repeat(64);
const word=a=>'0x'+a.slice(2).padStart(64,'0');
const claim=(id,raw='10000000',requestId='1',contract=box)=>({id,tx,category:'refund',contract,payer:contract,payerEvidence:'synthetic historical fixture',raw,requestId,amount:Number(raw)/1e6});
const transfer=(idx,raw='10000000',payer=box)=>({address:usdc,transactionHash:tx,logIndex:'0x'+idx.toString(16),blockNumber:'0x3030303',topics:[SIG.transfer,word(payer),word(wallet)],data:'0x'+BigInt(raw).toString(16)});
const run=(events,logs,status='0x1')=>reconcileRefunds(events,new Map([[tx,{status,logs}]]),wallet);
const total=events=>events.filter(e=>e.category==='refund-confirmed').reduce((n,e)=>n+BigInt(e.raw),0n);
const pending=events=>events.filter(e=>e.category==='refund-pending').length;
assert.equal(total(run([claim('a')],[transfer(10)])),10000000n);
assert.equal(total(run([claim('a'),claim('a')],[transfer(10)])),10000000n);
const dual=run([claim('a'),claim('b')],[transfer(10)]);assert.equal(total(dual),0n);assert.equal(pending(dual),2);
const separate=run([claim('a'),claim('b','5000000','2')],[transfer(10),transfer(11,'5000000')]);assert.equal(total(separate),15000000n);
assert.equal(total(run([claim('a'),claim('b','10000000','2')],[transfer(10),transfer(11)])),0n);
assert.equal(total(run([claim('a'),claim('b','10000000','2',other)],[transfer(10),transfer(11,'10000000',other)])),20000000n);
const extra={...claim(tx+':0xb','5000000'),category:'refund-transfer',contract:usdc};
const plus=run([claim('a'),extra],[transfer(10),transfer(11,'5000000',other)]);assert.equal(total(plus),10000000n);assert.equal(pending(plus),1);assert(plus.some(e=>e.id===extra.id));
const same={...claim(tx+':0xa'),category:'refund-transfer',contract:usdc};assert.equal(total(run([claim('a'),same],[transfer(10)])),10000000n);assert.equal(pending(run([claim('a'),same],[transfer(10)])),0);
assert.equal(total(run([claim('a')],[transfer(10,'10000000',other)])),0n);
assert.equal(total(run([claim('a')],[transfer(10)],'0x0')),0n);
assert.equal(pending(reconcileRefunds([claim('a')],new Map(),wallet)),1);
assert.equal(total(run([claim('a')],[transfer(10,'9999999')])),0n);
console.log('PASS: 12 refund receipt reconciliation cases; ambiguous mappings excluded, independent same-transaction records preserved');

// Real protocol payer is a treasury, not the emitting box.
assert.equal(total(run([{...claim('treasury'),payer:other}],[transfer(10,'10000000',other)])),10000000n);
assert.equal(total(run([{...claim('unknown'),payer:null}],[transfer(10)])),0n);
assert.equal(total(run([{...claim('treasury'),payer:other}],[transfer(10)])),0n);
const deferred={address:box,topics:[SIG.payoutDeferred,word(wallet)],data:'0x'+BigInt(10000000).toString(16)};
assert.equal(total(run([{...claim('deferred'),payer:other}],[transfer(10,'10000000',other),deferred])),0n);
const {historicalPayerEvidence}=await import('./worker/index.js');
const evidence=(updates=[])=>historicalPayerEvidence(word(other),word(other),word(usdc),word(usdc),updates);
assert.equal(evidence().payer,other);
assert.equal(evidence([{}]).payer,null,'any treasury change in entire block blocks attribution');
assert.equal(evidence(null).payer,null);
assert.equal(historicalPayerEvidence(null,word(other),word(usdc),word(usdc),[]).payer,null);
assert.equal(historicalPayerEvidence(word(box),word(other),word(usdc),word(usdc),[]).payer,null);
assert.equal(historicalPayerEvidence(word(other),word(other),word(box),word(usdc),[]).payer,null);
console.log('PASS: treasury payer, unknown historical data, changed treasury/token, deferred payout cases');
