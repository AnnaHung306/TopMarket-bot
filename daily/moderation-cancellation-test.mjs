import assert from 'node:assert/strict';
import { recordCancellation, removeGiveawayRole } from './moderation-cancellation.mjs';
import { eventTimes } from './time.mjs';

const mod='10000000000000001', target='10000000000000002';
const settings={guildId:'guild',modChannelId:'private',moderatorRoleId:'mod'};
const interaction={guildId:'guild',channelId:'private',user:{id:mod},member:{roles:{cache:new Map([['mod',true]])}}};
let calls=0, query;
const sql=async(parts,...values)=>{calls++;query={text:parts.join('?'),values};return [{newly_recorded:1,quiz_entries_removed:values.includes('quiz')?1:0}];};
const now=()=>eventTimes('2026-11-20','quiz').start+1000;
await assert.rejects(recordCancellation({interaction:{...interaction,channelId:'public'},settings,targetId:target,activity:'quiz',sql,now}),/MODERATOR_REQUIRED/);
await assert.rejects(recordCancellation({interaction:{...interaction,member:{roles:{cache:new Map()}}},settings,targetId:target,activity:'quiz',sql,now}),/MODERATOR_REQUIRED/);
await assert.rejects(recordCancellation({interaction,settings,targetId:target,activity:'both',sql,now}),/ACTIVITY_INVALID/);
assert.equal(calls,0);
const result=await recordCancellation({interaction,settings,targetId:target,activity:'quiz',sql,now});
assert.equal(result.day,'2026-11-20');
assert.equal(result.quizEntriesRemoved,1);
assert.equal(result.giveawayRemovalConfirmed,false);
assert.match(query.text,/'quiz'/);
assert.match(query.text,/DELETE FROM daily_entries/);
assert.equal(query.values.filter(v=>v===target).length,2);
assert.equal(query.values.filter(v=>v==='quiz').length,2);
const give=await recordCancellation({interaction,settings,targetId:target,activity:'giveaway',sql,now});
assert.equal(give.quizEntriesRemoved,0);
assert.equal(query.values.filter(v=>v==='giveaway').length,2);
await assert.rejects(recordCancellation({interaction,settings,targetId:target,activity:'quiz',sql,now:()=>eventTimes('2026-11-20','quiz').end}),/NO_ACTIVE_ACTIVITY/);
let hasRole=true, removed=0;
const member={manageable:true,roles:{cache:{has:()=>hasRole},remove:async()=>{removed++;hasRole=false;}}};
const guild={roles:{fetch:async()=>({position:1})},members:{fetchMe:async()=>({permissions:{has:()=>true},roles:{highest:{position:2}}}),fetch:async()=>member}};
await removeGiveawayRole({guild,roleId:'role',targetId:target});
assert.equal(hasRole,false);
assert.equal(removed,1);
await removeGiveawayRole({guild,roleId:'role',targetId:target});
assert.equal(removed,1,'retry does not remove unrelated roles');
member.manageable=false;
await assert.rejects(removeGiveawayRole({guild,roleId:'role',targetId:target}),/MEMBER_NOT_MANAGEABLE/);
member.manageable=true; hasRole=true; member.roles.remove=async()=>{};
await assert.rejects(removeGiveawayRole({guild,roleId:'role',targetId:target}),/ROLE_STILL_PRESENT/);
guild.members.fetchMe=async()=>({permissions:{has:()=>false},roles:{highest:{position:2}}});
await assert.rejects(removeGiveawayRole({guild,roleId:'role',targetId:target}),/ROLE_NOT_MANAGEABLE/);
console.log('moderator cancellation recording tests passed');
